'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {boot}=require('./harness-v7.cjs');
const script=fs.readFileSync('src/pixel-art-v010.js','utf8');
const css=fs.readFileSync('src/pixel-art-v010.css','utf8');
const page=fs.readFileSync('index.html','utf8');
const build=fs.readFileSync('scripts/build.py','utf8');
const {g,sandbox}=boot();
const art=vm.runInContext('({PIXEL_ART_V010,pixelCachedCanvas,RASTER_DATA,PROP_CELL,MONSTER_CELL,worldFloors})',sandbox);
assert.equal(art.PIXEL_ART_V010.version,'0.10.0');
assert.equal(art.PIXEL_ART_V010.spriteCell,2);
assert.equal(Object.keys(art.MONSTER_CELL).length,18);
assert.equal(Object.keys(art.PROP_CELL).length,14);
assert.equal(art.worldFloors.length,16);
assert.ok(page.includes('PIXEL_ART_V010'),'standalone build includes pixel processing');
assert.ok(page.includes('data-art-version="0.10.0"'),'standalone page includes new styling');
assert.ok(css.includes('HellboundHeading'),'titles use offline heading font');
assert.ok(css.includes('image-rendering:pixelated'),'previews and item icons stay crisp');
assert.ok(build.includes("src/pixel-art-v010.js"),'source module included in build');
assert.ok(build.includes("src/pixel-art-v010.css"),'style module included in build');
assert.equal(g.Terrain.free(0,0),true,'terrain collision logic still loads');
const sample=vm.runInContext('surface(96,128)',sandbox);
const output=art.pixelCachedCanvas(sample,2,'actor');
assert.strictEqual(output,art.pixelCachedCanvas(sample,2,'actor'),'pixelized artwork caches by source');
assert.notStrictEqual(output,art.pixelCachedCanvas(sample,3,'prop'),'distinct atlas resolutions retain own cache');
assert.ok(script.includes('const bootBeforePixelV010=boot'),'build labels the version at boot');
console.log('PASS v0.10.0: cached pixel art, hero/enemy/boss coverage, scenery, four-act terrain, UI typography, standalone build and unchanged collision API');
